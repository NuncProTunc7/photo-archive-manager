"""`pam --help` and every subcommand's `--help`, held to a transcript recorded BY HAND.

M14 Task 4 Step 1 moved the `faces` group's registrations out of `pam/cli.py` into
`pam/cli_faces.py`. The plan calls it a PURE MOVE, and this is what makes that a measured claim
rather than a promise: `tests/fixtures/cli_help/before-t4a.txt` was captured from the tree at
`7c4d393`, BEFORE the move, and committed as data. It is never regenerated by the code under
test - a golden file written by the thing it checks agrees with that thing by construction.

M14 Task 4c ADDED `pam start` (U9): its own screen and its line in `pam --help`'s command list
were typed into the transcript BY HAND, from the built command's output read on the console -
the only edits to it since the move, with one more: M14 Task 6 (ruling B1) made `pam review`'s
server rename, so its "Renames nothing." was false; its two lines were retyped BY HAND. Every
other screen is still the pre-move recording. M15 Task 12 ADDED `pam update` (E2): its screen and
its line in `pam --help` were typed in BY HAND, from the built command's output read beside them.

THE COMMAND LIST IS CHECKED IN BOTH DIRECTIONS. The transcript's own `=== pam ... --help` headers
are the expected set; the live click tree is walked for the actual set. A command dropped by the
move (registered nowhere) and a command added without its help being recorded are both red, and
the header count is a literal floor so an emptied or truncated transcript cannot pass as "every
recorded command still matches".

Rendered at a fixed width of 80 and with `prog_name="pam"`, so the transcript does not depend on
the console the suite happens to run in.
"""

from pathlib import Path

import click
from click.testing import CliRunner

from pam import cli_faces
from pam.cli import ARCHIVE_HELP, cli

GOLDEN = Path(__file__).resolve().parent / "fixtures" / "cli_help" / "before-t4a.txt"
HEADER = "=== pam "

# The 24 help screens at `7c4d393`, spelled from design 12's command table, NOT read off the
# transcript or the tree: bare `pam`, thirteen top-level commands, the three groups' ten
# subcommands - plus `start` (U9, M14 Task 4c): 25 - plus `update` (E2, M15 Task 12): 26. A
# literal, so the transcript and the tree cannot shrink together.
EXPECTED_SCREENS = frozenset(
    {
        "",
        "apply",
        "doctor",
        "enrich",
        "faces",
        "faces calibrate",
        "faces cluster",
        "faces export",
        "faces label",
        "faces manifest",
        "faces purge",
        "forget",
        "models",
        "models pull",
        "plan",
        "report",
        "report duplicates",
        "report session",
        "report skipped",
        "review",
        "scan",
        "start",
        "status",
        "undo",
        "update",
        "verify",
    }
)
assert len(EXPECTED_SCREENS) == 26, len(EXPECTED_SCREENS)


def _recorded() -> dict[str, str]:
    """The transcript, as `{command path: help text}`. Text mode: git may check it out CRLF."""
    screens: dict[str, str] = {}
    current: str | None = None
    for line in GOLDEN.read_text(encoding="utf-8").splitlines(keepends=True):
        if line.startswith(HEADER):
            current = line[len(HEADER) :].rstrip("\n").removesuffix("--help").strip()
            screens[current] = ""
            continue
        assert current is not None, "the transcript must open with a header"
        screens[current] += line
    return screens


def _live_paths(group: click.Command, prefix: tuple[str, ...] = ()) -> set[str]:
    paths = {" ".join(prefix)}
    if isinstance(group, click.Group):
        for name, command in group.commands.items():
            paths |= _live_paths(command, (*prefix, name))
    return paths


def _render(path: str) -> str:
    args = [*path.split(), "--help"] if path else ["--help"]
    result = CliRunner().invoke(cli, args, terminal_width=80, prog_name="pam")
    assert result.exit_code == 0, (path, result.output)
    return result.output


def test_the_transcript_and_the_live_tree_list_exactly_the_spelled_commands():
    recorded = _recorded()
    assert set(recorded) == EXPECTED_SCREENS
    assert _live_paths(cli) == EXPECTED_SCREENS


def test_every_help_screen_is_byte_identical_to_the_transcript_recorded_before_the_move():
    recorded = _recorded()
    for path in sorted(EXPECTED_SCREENS):
        assert _render(path) == recorded[path], f"`pam {path} --help` changed"


def test_the_faces_group_is_registered_from_cli_faces_and_shares_reports_archive_help():
    """The move's two seams: the group `cli` serves IS `cli_faces.faces` (not a second
    definition left behind), and calibrate's --archive help, spelled again in `cli_faces`
    because `cli` imports it, is word for word `pam report`'s."""
    assert cli.commands["faces"] is cli_faces.faces
    assert cli_faces.ARCHIVE_HELP == ARCHIVE_HELP
